import numpy as np

def find_critical_load(L, E, A, r, c, e, sigma_allow):
    """
    L: אורך במ"מ
    E: מודול אלסטיות ב-MPa
    A: שטח חתך בממ"ר
    r: רדיוס אינרציה במ"מ
    c: מרחק לסיב קיצוני במ"מ
    e: אקסצנטריות במ"מ
    sigma_allow: מאמץ מותר ב-MPa
    
    Return: העומס P בניוטון (float)
    """
    
    # 1. הגדרת פונקציית העזר שאת השורש שלה נרצה למצוא
    def f(P):
        if P == 0:
            return -sigma_allow
        
        # חישוב הארגומנט בתוך הקוסינוס (ברדיאנים)
        # הוספת max(P, 0) קטן כדי למנוע ערכים שליליים תחת השורש במהלך החיפוש הנומרי
        angle = (L / (2 * r)) * np.sqrt(P / (E * A))
        
        # חישוב המאמץ המקסימלי לפי נוסחת הסקנט
        sigma_max = (P / A) * (1 + (e * c / r**2) * (1 / np.cos(angle)))
        
        # מחזירים את ההפרש מהמאמץ המותר
        return sigma_max - sigma_allow

    # 2. קביעת חסמים לשיטת החצייה (Bisection)
    # חסם תחתון: עומס אפס
    p_min = 0.0
    
    # חסם עליון: עומס אוילר התיאורטי P_cr = (pi^2 * E * I) / L^2 כאשר I = A * r^2
    p_euler = (np.pi**2 * E * (A * r**2)) / (L**2)
    
    # כדי להימנע מנקודת הסינגולריות של הקוסינוס בעומס אוילר (שם המכנה מתאפס),
    # נבחר חסם עליון מעט קטן יותר מעומס אוילר (למשל 99.9%)
    p_max = 0.999 * p_euler

    # 3. הרצת שיטת החצייה למציאת השורש בדיוק הנדרש
    #xtol מגדיר את הדיוק הנדרש עבור ערך ה-P שנמצא
    critical_load = bisect(f, p_min, p_max, xtol=1e-4)
    
    return float(critical_load)
